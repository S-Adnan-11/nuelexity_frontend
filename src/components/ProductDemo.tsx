import { memo, useLayoutEffect, useRef } from "react";
import { ArrowUp, Check, ChevronDown, Globe, Square } from "lucide-react";
import { Answer } from "./Answer";
import { BrandLogo, BrandMark } from "./Brand";
import { SourceCards } from "./SourceCards";
import { demoAnswer, demoFollowUp, demoFollowUpAnswer, demoFrame, demoModels, demoQuestion, demoScroll, demoSources } from "../lib/product-demo";
import { useDemoPlayback } from "../lib/useDemoPlayback";

const DemoAnswer = memo(Answer);
function DemoResponse({ content, sourceCount, researching }: { content: string; sourceCount: number; researching: boolean }) {
  return <div className="message assistant">
    <div className="answer-heading"><BrandMark /><span>Nuelexity</span></div>
    <div className="demo-sources" data-count={sourceCount}><SourceCards sources={demoSources} /></div>
    <DemoAnswer content={content} sources={demoSources} />
    {researching && <p className="stream-status"><span className="status-dot" />Researching…</p>}
  </div>;
}
export function ProductDemo() {
  const { ref, elapsed, playing, reduced } = useDemoPlayback();
  const frame = demoFrame(elapsed);
  const scroll = useRef<HTMLDivElement>(null);
  const measurements = useRef<HTMLDivElement>(null);
  const stops = useRef<number[]>([]);
  const clock = useRef({ time: frame.time, reduced });
  clock.current = { time: frame.time, reduced };
  function alignPane() {
    const pane = scroll.current;
    if (!pane) return;
    const target = clock.current.reduced ? pane.scrollHeight : demoScroll(clock.current.time, stops.current);
    pane.scrollTop = Math.min(Math.max(0, pane.scrollHeight - pane.clientHeight), target);
  }
  useLayoutEffect(() => {
    const pane = scroll.current, measure = measurements.current;
    if (!pane || !measure) return;
    const resize = () => {
      const top = measure.getBoundingClientRect().top;
      const paragraphs = measure.querySelectorAll<HTMLElement>(".answer-text > p");
      const position = (node: Element | undefined) => node ? node.getBoundingClientRect().top - top : 0;
      const firstEnd = measure.querySelector<HTMLElement>(".demo-measure-first")!;
      const second = measure.querySelector<HTMLElement>(".demo-measure-second")!;
      // Read the sources first, then move to paragraph beginnings and the ending.
      stops.current = [0, position(paragraphs[0]), position(paragraphs[1]),
        firstEnd.offsetHeight - pane.clientHeight + 24, position(second),
        position(paragraphs[3]), position(paragraphs[4]), measure.scrollHeight - pane.clientHeight + 24].map(n => Math.max(0, n));
      alignPane();
    };
    const observer = new ResizeObserver(resize);
    observer.observe(measure); observer.observe(pane);
    resize();
    return () => observer.disconnect();
  }, []);
  useLayoutEffect(() => {
    // The frame's single clock drives camera and pane. Never focus/scroll the page.
    alignPane();
  });
  return <figure ref={ref} className="product-demo" aria-describedby="demo-description" data-playing={playing} data-demo-phase={frame.phase} data-demo-time={Math.round(frame.time)}>
    <p id="demo-description" className="sr-only">An illustrative Nuelexity search: “{demoQuestion}”, then “{demoFollowUp}”. Explore sources and an explanation of superposition, interference and measurement. This is a prepared example, not a live search or a response generated by the selected models.</p>
    <div className="demo-window" aria-hidden="true" inert>
      <div className="demo-topbar"><BrandLogo /><span><Globe size={14} /> Search the web</span></div>
      <div className="demo-stage">
        <div className="demo-playback" style={{ opacity: frame.opacity, transform: `scale(${1 + frame.zoom * (reduced ? 0 : .045)})` }}>
          <div ref={scroll} className="demo-viewport">
            {!frame.submitted ? <div className="demo-welcome welcome">
              <BrandMark size={48} /><p className="eyebrow">FOR THE CURIOUS MINDS</p>
              <h3>Where curiosity<br /><em>finds its answers.</em></h3>
              <p>Ask a question. Explore the sources.</p>
            </div> : <div className="demo-thread">
              <div className="message user"><p>{demoQuestion}</p></div>
              <DemoResponse content={frame.answer} sourceCount={frame.sourceCount} researching={frame.researching && !frame.followUpSubmitted} />
              {frame.followUpSubmitted && <div className="demo-follow-up">
                <div className="message user"><p>{demoFollowUp}</p></div>
                <DemoResponse content={frame.followUpAnswer} sourceCount={frame.followUpSourceCount} researching={frame.researching} />
              </div>}
            </div>}
          </div>
          <div className="demo-composer composer">
            <div className="demo-draft">{frame.draft || <span>{frame.submitted ? "Ask a follow-up…" : "Ask anything…"}</span>}{!!frame.draft && <span className="demo-caret" />}</div>
            <div className="composer-toolbar"><span className="search-indicator"><Globe size={14} />Web · Sources</span>
              <span className="demo-model">{frame.model}<ChevronDown size={12} /></span>
              <span className="send-button">{frame.researching ? <Square size={14} /> : <ArrowUp size={18} />}</span>
            </div>
            {frame.modelMenu && <div className="demo-model-menu"><span>Choose a model</span>{["GPT-OSS 20B", ...demoModels].map(label => <div key={label} className={label === demoModels[1] ? "is-next" : ""}>{label}{label === demoModels[0] && <Check size={14} />}</div>)}</div>}
          </div>
        </div>
        <div ref={measurements} className="demo-measurements">
          <div className="demo-measure-first"><div className="message user"><p>{demoQuestion}</p></div><DemoResponse content={demoAnswer} sourceCount={3} researching={false} /></div>
          <div className="demo-measure-second"><div className="message user"><p>{demoFollowUp}</p></div><DemoResponse content={demoFollowUpAnswer} sourceCount={3} researching={false} /></div>
        </div>
      </div>
    </div>
    <figcaption>Illustrative example.<span>Explore the references: <a href={demoSources[0]!.url} target="_blank" rel="noopener noreferrer">Microsoft Quantum</a> · <a href={demoSources[2]!.url} target="_blank" rel="noopener noreferrer">IBM Quantum</a></span></figcaption>
  </figure>;
}
